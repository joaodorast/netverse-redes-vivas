"""Check the one-file-per-commit policy without rewriting history."""
import re
import subprocess

def git(*args):
    return subprocess.check_output(['git', *args], encoding='utf-8').strip()

commits = git('rev-list', '--reverse', 'HEAD').splitlines()
violations = []
for commit in commits:
    paths = git('diff-tree', '--root', '--no-commit-id', '--name-only', '-r', commit).splitlines()
    message = git('show', '-s', '--format=%B', commit)
    if len(paths) != 1:
        violations.append(f'{commit[:8]}: {len(paths)} arquivos')
    if not re.match(r'^(feat|fix|refactor|style|perf|docs|test|chore|build|ci)\([\w-]+\): .+', message):
        violations.append(f'{commit[:8]}: formato de mensagem inválido')
    if 'co-authored-by:' in message.lower() or 'generated by ai' in message.lower():
        violations.append(f'{commit[:8]}: trailer não permitido')
if violations:
    raise SystemExit('\n'.join(violations))
print(f'{len(commits)} commits validados: exatamente um arquivo por commit; formato convencional; sem trailers automáticos de IA.')
